"""Generate Earth Control v1 JSON Schema and TypeScript from the authority's argument models."""
import json
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from blackfong_ecosystem.earth.contracts import Command,COMMAND_ARGUMENTS

def ts(schema):
    if "anyOf" in schema:return " | ".join(ts(value) for value in schema["anyOf"])
    if "const" in schema:return json.dumps(schema["const"])
    if "enum" in schema:return " | ".join(json.dumps(value) for value in schema["enum"])
    kind=schema.get("type")
    if kind=="array":return "("+ts(schema["items"])+")[]"
    if kind=="object":
        required=schema.get("required",[])
        return "{ "+" ".join(json.dumps(key)+("" if key in required else "?")+": "+ts(value)+";" for key,value in schema.get("properties",{}).items())+" }"
    return {"string":"string","number":"number","integer":"number","boolean":"boolean","null":"null"}.get(kind,"unknown")

variants=[];arguments={}
for name,model in COMMAND_ARGUMENTS.items():
    schema=Command.model_json_schema()
    schema["properties"]["command"]={"const":name}
    schema["properties"]["arguments"]=model.model_json_schema()
    variants.append(schema)
    arguments[name]=ts(model.model_json_schema())
json_text=json.dumps({"$schema":"https://json-schema.org/draft/2020-12/schema","title":"Earth Control v1","oneOf":variants},indent=2)+"\n"
ts_text="// Generated by tools/export_earth_control_contracts.py.\nexport type EarthArguments = {\n"+"\n".join("  "+json.dumps(name)+": "+value+";" for name,value in arguments.items())+"\n};\nexport type EarthCommandName = keyof EarthArguments;\nexport type EarthRequest = { [N in EarthCommandName]: {schema_version: '1.0'; request_id: string; scene_id: string; command: N; arguments: EarthArguments[N]} }[EarthCommandName];\n"
outputs={ROOT/"blackfong_ecosystem/contracts/earth_control_v1.schema.json":json_text,ROOT/"EarthGlass/obeos-earth/src/earthControl.generated.ts":ts_text}
for path,content in outputs.items():
    if "--check" in sys.argv:assert path.read_text(encoding="utf-8")==content,f"Generated contract is stale: {path.name}"
    else:path.write_text(content,encoding="utf-8")
